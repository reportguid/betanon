function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const pathname = useRouterState({ select: (s) => s.location.pathname });
  const { state } = useEtherox();
  useEffect(() => {
    if (typeof document === "undefined") return;
    document.documentElement.classList.toggle("reduce-motion", !!state.reduceMotion);
  }, [state.reduceMotion]);
  const animClass = state.reduceMotion ? "" : "ex-route-in";
  return (
    <QueryClientProvider client={queryClient}>
      <CurrencyBackdrop />
      <div key={pathname} className={animClass}>
        <Outlet />
      </div>
      <BottomNav />
      <SonnerToaster
        toastOptions={{
          className: state.reduceMotion ? "" : "ex-slide-up",
        }}
      />
    </QueryClientProvider>
  );
}
